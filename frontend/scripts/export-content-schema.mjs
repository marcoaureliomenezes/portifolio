#!/usr/bin/env node
/**
 * export-content-schema.mjs — T-RD-11 (AC-RD-08)
 *
 * Exports the canonical content contract (scripts/content-schema.mjs) as
 * versioned JSON Schema at public/content/schema/v1.json. The external
 * admin-panel project consumes this artifact to render schema-driven forms —
 * it is the ONLY coupling between the two projects.
 *
 * Deterministic output (sorted, stable stringify) so CI can diff-check that
 * the committed artifact matches the schema source.
 *
 * Usage: node scripts/export-content-schema.mjs [--check]
 *   --check  exit 1 if the committed artifact differs (CI mode, no write)
 */

import { writeFileSync, readFileSync, mkdirSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { zodToJsonSchema } from "zod-to-json-schema";
import { ContentDataSchema } from "./content-schema.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const OUT = resolve(__dirname, "../public/content/schema/v1.json");

const jsonSchema = zodToJsonSchema(ContentDataSchema, {
  name: "PortfolioContentV1",
  target: "jsonSchema7",
});

const artifact = `${JSON.stringify(
  {
    $comment:
      "GENERATED by scripts/export-content-schema.mjs from scripts/content-schema.mjs — do not edit by hand.",
    ...jsonSchema,
  },
  null,
  2,
)}\n`;

if (process.argv.includes("--check")) {
  const current = existsSync(OUT) ? readFileSync(OUT, "utf-8") : "";
  if (current !== artifact) {
    console.error(
      "[export-content-schema] DRIFT: public/content/schema/v1.json does not match scripts/content-schema.mjs. Run: npm run schema:export",
    );
    process.exit(1);
  }
  console.log("[export-content-schema] OK — committed artifact matches the schema source.");
} else {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, artifact);
  console.log(`[export-content-schema] wrote ${OUT}`);
}
